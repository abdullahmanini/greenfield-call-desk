"""Build assets/site-data.js from data/accounts.json and check every record.

Run from the project folder:  python3 python/build_site_data.py
"""
import json
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASOF = "2026-11-02"
WINDOW_FROM, WINDOW_TO = "2026-08-01", "2026-11-01"
TYPES = {"expansion", "acquisition", "funding", "digital_initiative", "product_launch",
         "leadership_hire", "contract_win", "grant"}
PROVINCES = {"AB", "BC", "MB", "NB", "NL", "NS", "ON", "PE", "QC", "SK"}
REQUIRED = ["name", "city", "province", "sector", "trigger_type", "trigger_date", "trigger_summary",
            "source_url", "source_publisher", "personas", "cloud_angle", "confidence", "hook", "hook_short"]
SOURCE_NOTE = ("Sources are company press releases, newswires, government releases and news outlets; "
               "each was opened and checked against the event it supports.")


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")[:40]


def as_date(s):
    parts = [int(p) for p in s.split("-")]
    return date(parts[0], parts[1], parts[2] if len(parts) > 2 else 15)


def main():
    accounts = json.loads((ROOT / "data" / "accounts.json").read_text(encoding="utf-8"))
    problems, seen = [], set()
    for a in accounts:
        tag = a.get("name", "?")
        for k in REQUIRED:
            if not a.get(k):
                problems.append(f"{tag}: missing {k}")
        if a.get("trigger_type") not in TYPES:
            problems.append(f"{tag}: unknown trigger_type {a.get('trigger_type')}")
        if a.get("province") not in PROVINCES:
            problems.append(f"{tag}: unknown province {a.get('province')}")
        if a.get("confidence") not in {"high", "medium"}:
            problems.append(f"{tag}: confidence must be high or medium")
        try:
            d = as_date(a["trigger_date"])
            if not (as_date(WINDOW_FROM) <= d <= as_date(WINDOW_TO)):
                problems.append(f"{tag}: event date {a['trigger_date']} outside window")
        except (KeyError, ValueError):
            problems.append(f"{tag}: bad trigger_date")
        if not str(a.get("source_url", "")).startswith("https://"):
            problems.append(f"{tag}: source_url must be https")
        a["id"] = slug(a["name"])
        if a["id"] in seen:
            problems.append(f"{tag}: duplicate id {a['id']}")
        seen.add(a["id"])
        a.setdefault("employees", "unknown")
        a.setdefault("employees_source", None)
        a.setdefault("second_source_url", None)
    if problems:
        print("\n".join(problems))
        sys.exit(1)

    payload = {"asof": ASOF, "window_from": WINDOW_FROM, "window_to": WINDOW_TO,
               "source_note": SOURCE_NOTE, "accounts": accounts}
    out = ROOT / "assets" / "site-data.js"
    out.write_text("/* Generated by python/build_site_data.py from data/accounts.json. Do not edit by hand. */\n"
                   "window.GCD = " + json.dumps(payload, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    provs = sorted({a["province"] for a in accounts})
    print(f"wrote {out.relative_to(ROOT)}: {len(accounts)} accounts, provinces {', '.join(provs)}")


if __name__ == "__main__":
    main()
